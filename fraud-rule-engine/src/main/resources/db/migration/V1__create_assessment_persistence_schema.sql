CREATE TABLE processed_event (
    event_id VARCHAR(128) PRIMARY KEY,
    transaction_id VARCHAR(128) NOT NULL,
    account_id VARCHAR(128),
    customer_id VARCHAR(128),
    amount NUMERIC(38, 18) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    category VARCHAR(64) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    merchant_id VARCHAR(128),
    location VARCHAR(128),
    beneficiary_id VARCHAR(128),
    origin_country VARCHAR(2),
    beneficiary_country VARCHAR(2),
    channel VARCHAR(32),
    schema_version VARCHAR(16) NOT NULL,
    correlation_id VARCHAR(128),
    qualifying_activity BOOLEAN NOT NULL DEFAULT FALSE,
    ingested_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_processed_event_one_subject
        CHECK ((account_id IS NOT NULL AND customer_id IS NULL)
            OR (account_id IS NULL AND customer_id IS NOT NULL)),
    CONSTRAINT ck_processed_event_amount CHECK (amount >= 0),
    CONSTRAINT ck_processed_event_currency
        CHECK (CHAR_LENGTH(currency) = 3 AND currency = UPPER(currency)),
    CONSTRAINT ck_processed_event_schema_version CHECK (schema_version = '1.0.0')
);

CREATE INDEX ix_processed_event_account_time
    ON processed_event (account_id, occurred_at DESC, event_id);
CREATE INDEX ix_processed_event_customer_time
    ON processed_event (customer_id, occurred_at DESC, event_id);
CREATE INDEX ix_processed_event_qualifying_activity
    ON processed_event (account_id, qualifying_activity, occurred_at DESC);

CREATE TABLE behavioral_baseline (
    baseline_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_type VARCHAR(16) NOT NULL,
    subject_id VARCHAR(128) NOT NULL,
    version BIGINT NOT NULL,
    sample_size INTEGER NOT NULL,
    average_amount NUMERIC(38, 18) NOT NULL,
    data_as_of TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_behavioral_baseline_subject_version
        UNIQUE (subject_type, subject_id, version),
    CONSTRAINT ck_behavioral_baseline_subject_type
        CHECK (subject_type IN ('ACCOUNT', 'CUSTOMER')),
    CONSTRAINT ck_behavioral_baseline_version CHECK (version > 0),
    CONSTRAINT ck_behavioral_baseline_sample_size CHECK (sample_size >= 0),
    CONSTRAINT ck_behavioral_baseline_average CHECK (average_amount >= 0)
);

CREATE INDEX ix_behavioral_baseline_latest
    ON behavioral_baseline (subject_type, subject_id, version DESC);

CREATE TABLE behavioral_baseline_category (
    baseline_id BIGINT NOT NULL REFERENCES behavioral_baseline (baseline_id) ON DELETE CASCADE,
    category VARCHAR(64) NOT NULL,
    transaction_count BIGINT NOT NULL,
    PRIMARY KEY (baseline_id, category),
    CONSTRAINT ck_baseline_category_count CHECK (transaction_count >= 0)
);

CREATE TABLE account_activity (
    activity_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_type VARCHAR(16) NOT NULL,
    subject_id VARCHAR(128) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    definition_version VARCHAR(64) NOT NULL,
    data_as_of TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_account_activity_subject_type
        CHECK (subject_type IN ('ACCOUNT', 'CUSTOMER'))
);

CREATE INDEX ix_account_activity_latest
    ON account_activity (subject_type, subject_id, occurred_at DESC, activity_id DESC);

CREATE TABLE rule_configuration_snapshot (
    snapshot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_version BIGINT NOT NULL,
    effective_at TIMESTAMP WITH TIME ZONE NOT NULL,
    captured_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_rule_snapshot_version CHECK (snapshot_version > 0),
    CONSTRAINT uq_rule_snapshot_version_effective UNIQUE (snapshot_version, effective_at)
);

CREATE INDEX ix_rule_snapshot_effective
    ON rule_configuration_snapshot (effective_at DESC, snapshot_id DESC);

CREATE TABLE rule_configuration (
    configuration_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_id BIGINT NOT NULL REFERENCES rule_configuration_snapshot (snapshot_id) ON DELETE CASCADE,
    rule_code VARCHAR(64) NOT NULL,
    version BIGINT NOT NULL,
    enabled BOOLEAN NOT NULL,
    effective_from TIMESTAMP WITH TIME ZONE NOT NULL,
    effective_until TIMESTAMP WITH TIME ZONE,
    score_contribution NUMERIC(38, 18) NOT NULL,
    CONSTRAINT uq_rule_configuration_snapshot_code UNIQUE (snapshot_id, rule_code),
    CONSTRAINT ck_rule_configuration_version CHECK (version > 0),
    CONSTRAINT ck_rule_configuration_score CHECK (score_contribution >= 0),
    CONSTRAINT ck_rule_configuration_interval
        CHECK (effective_until IS NULL OR effective_until > effective_from)
);

CREATE INDEX ix_rule_configuration_code_version
    ON rule_configuration (rule_code, version DESC);

CREATE TABLE rule_configuration_parameter (
    configuration_id BIGINT NOT NULL
        REFERENCES rule_configuration (configuration_id) ON DELETE CASCADE,
    parameter_name VARCHAR(64) NOT NULL,
    parameter_value VARCHAR(256) NOT NULL,
    PRIMARY KEY (configuration_id, parameter_name)
);

CREATE TABLE rule_configuration_audit (
    audit_id UUID PRIMARY KEY,
    rule_code VARCHAR(64) NOT NULL,
    configuration_version BIGINT NOT NULL,
    action VARCHAR(16) NOT NULL,
    actor_reference VARCHAR(128) NOT NULL,
    reason_code VARCHAR(64) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_rule_configuration_audit_version CHECK (configuration_version > 0),
    CONSTRAINT ck_rule_configuration_audit_action
        CHECK (action IN ('CREATED', 'UPDATED', 'DISABLED', 'DELETED'))
);

CREATE INDEX ix_rule_configuration_audit_rule_time
    ON rule_configuration_audit (rule_code, occurred_at DESC, audit_id);

CREATE TABLE reference_data_snapshot (
    snapshot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    effective_at TIMESTAMP WITH TIME ZONE NOT NULL,
    captured_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_reference_snapshot_effective
    ON reference_data_snapshot (effective_at DESC, snapshot_id DESC);

CREATE TABLE reference_data_version (
    snapshot_id BIGINT NOT NULL
        REFERENCES reference_data_snapshot (snapshot_id) ON DELETE CASCADE,
    data_type VARCHAR(32) NOT NULL,
    version BIGINT NOT NULL,
    PRIMARY KEY (snapshot_id, data_type),
    CONSTRAINT ck_reference_data_version_type
        CHECK (data_type IN ('INTERNAL_WATCHLIST', 'COUNTRY_RISK')),
    CONSTRAINT ck_reference_data_version_positive CHECK (version > 0)
);

CREATE TABLE reference_data_entry (
    entry_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_id BIGINT NOT NULL
        REFERENCES reference_data_snapshot (snapshot_id) ON DELETE CASCADE,
    data_type VARCHAR(32) NOT NULL,
    subject_type VARCHAR(32) NOT NULL,
    normalized_value VARCHAR(128) NOT NULL,
    reason_code VARCHAR(64) NOT NULL,
    effective_from TIMESTAMP WITH TIME ZONE NOT NULL,
    effective_until TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_reference_entry_type
        CHECK (data_type IN ('INTERNAL_WATCHLIST', 'COUNTRY_RISK')),
    CONSTRAINT ck_reference_entry_subject
        CHECK (subject_type IN ('ACCOUNT', 'CUSTOMER', 'MERCHANT', 'BENEFICIARY', 'COUNTRY')),
    CONSTRAINT ck_reference_entry_country_type
        CHECK ((data_type = 'COUNTRY_RISK' AND subject_type = 'COUNTRY')
            OR (data_type = 'INTERNAL_WATCHLIST' AND subject_type <> 'COUNTRY')),
    CONSTRAINT ck_reference_entry_interval
        CHECK (effective_until IS NULL OR effective_until > effective_from),
    CONSTRAINT uq_reference_entry UNIQUE
        (snapshot_id, data_type, subject_type, normalized_value, effective_from)
);

CREATE INDEX ix_reference_entry_lookup
    ON reference_data_entry (snapshot_id, data_type, subject_type, normalized_value);

CREATE TABLE fraud_evaluation (
    evaluation_id UUID PRIMARY KEY,
    event_id VARCHAR(128) NOT NULL UNIQUE REFERENCES processed_event (event_id),
    evaluated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    decision VARCHAR(24) NOT NULL,
    processing_status VARCHAR(24) NOT NULL,
    configuration_snapshot_id BIGINT NOT NULL
        REFERENCES rule_configuration_snapshot (snapshot_id),
    reference_snapshot_id BIGINT REFERENCES reference_data_snapshot (snapshot_id),
    reference_context_state VARCHAR(16) NOT NULL,
    reference_missing_reason VARCHAR(32),
    reference_unavailable_source VARCHAR(32),
    reference_unavailable_reason VARCHAR(32),
    reference_retryable BOOLEAN,
    reference_checked_at TIMESTAMP WITH TIME ZONE,
    reference_occurred_at TIMESTAMP WITH TIME ZONE,
    reference_retrieved_at TIMESTAMP WITH TIME ZONE,
    reference_data_as_of TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_evaluation_decision
        CHECK (decision IN ('FLAGGED', 'NOT_FLAGGED', 'UNDETERMINED')),
    CONSTRAINT ck_evaluation_status
        CHECK (processing_status IN ('RECEIVED', 'EVALUATING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_evaluation_reference_state
        CHECK (reference_context_state IN ('AVAILABLE', 'MISSING', 'UNAVAILABLE')),
    CONSTRAINT ck_evaluation_reference_snapshot
        CHECK ((reference_context_state = 'AVAILABLE' AND reference_snapshot_id IS NOT NULL)
            OR (reference_context_state <> 'AVAILABLE' AND reference_snapshot_id IS NULL)),
    CONSTRAINT ck_evaluation_reference_details
        CHECK (
            (reference_context_state = 'AVAILABLE'
                AND reference_retrieved_at IS NOT NULL
                AND reference_data_as_of IS NOT NULL
                AND reference_missing_reason IS NULL
                AND reference_unavailable_source IS NULL
                AND reference_unavailable_reason IS NULL
                AND reference_retryable IS NULL
                AND reference_checked_at IS NULL
                AND reference_occurred_at IS NULL)
            OR (reference_context_state = 'MISSING'
                AND reference_missing_reason IS NOT NULL
                AND reference_checked_at IS NOT NULL
                AND reference_unavailable_source IS NULL
                AND reference_unavailable_reason IS NULL
                AND reference_retryable IS NULL
                AND reference_retrieved_at IS NULL
                AND reference_data_as_of IS NULL
                AND reference_occurred_at IS NULL)
            OR (reference_context_state = 'UNAVAILABLE'
                AND reference_unavailable_source IS NOT NULL
                AND reference_unavailable_reason IS NOT NULL
                AND reference_retryable IS NOT NULL
                AND reference_occurred_at IS NOT NULL
                AND reference_missing_reason IS NULL
                AND reference_checked_at IS NULL
                AND reference_retrieved_at IS NULL
                AND reference_data_as_of IS NULL)
        ),
    CONSTRAINT ck_evaluation_failure_decision
        CHECK (processing_status <> 'FAILED' OR decision = 'UNDETERMINED')
);

CREATE INDEX ix_fraud_evaluation_time
    ON fraud_evaluation (evaluated_at DESC, evaluation_id DESC);
CREATE INDEX ix_fraud_evaluation_decision_time
    ON fraud_evaluation (decision, evaluated_at DESC, evaluation_id DESC);

CREATE TABLE evaluation_rule_result (
    result_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_id UUID NOT NULL REFERENCES fraud_evaluation (evaluation_id) ON DELETE CASCADE,
    rule_code VARCHAR(64) NOT NULL,
    configuration_version BIGINT NOT NULL,
    outcome VARCHAR(24),
    failure_code VARCHAR(40),
    retryable BOOLEAN,
    score_contribution NUMERIC(38, 18) NOT NULL,
    reason_code VARCHAR(64),
    CONSTRAINT uq_evaluation_rule UNIQUE (evaluation_id, rule_code),
    CONSTRAINT ck_evaluation_rule_configuration_version CHECK (configuration_version > 0),
    CONSTRAINT ck_evaluation_rule_score CHECK (score_contribution >= 0),
    CONSTRAINT ck_evaluation_rule_state
        CHECK ((outcome IN ('MATCH', 'NO_MATCH', 'NOT_APPLICABLE')
                AND failure_code IS NULL AND retryable IS NULL)
            OR (outcome IS NULL AND failure_code IS NOT NULL AND retryable IS NOT NULL
                AND score_contribution = 0)),
    CONSTRAINT ck_evaluation_match_reason
        CHECK ((outcome <> 'MATCH' OR reason_code IS NOT NULL)
            AND (outcome = 'MATCH' OR score_contribution = 0))
);

CREATE INDEX ix_evaluation_rule_code ON evaluation_rule_result (rule_code, evaluation_id);

CREATE TABLE evaluation_evidence_attribute (
    result_id BIGINT NOT NULL REFERENCES evaluation_rule_result (result_id) ON DELETE CASCADE,
    attribute_name VARCHAR(64) NOT NULL,
    attribute_value VARCHAR(128) NOT NULL,
    PRIMARY KEY (result_id, attribute_name)
);
